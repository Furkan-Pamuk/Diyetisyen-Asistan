/// Resmi gramaj listesini (EK-1) ice aktarir.
/// - Olmayan stok kartlarini acar (stok 0, esik 0).
/// - Adi ayni olan tarifleri atlar.
/// Cok kez calistirilabilir; tekrar kayit olusturmaz.
/// Donus: {'items': acilan kart, 'recipes': eklenen tarif}.
extension OfficialRecipesImport on AppStore {
  Future<Map<String, int>> importOfficialRecipes() async {
    var itemCount = 0;
    var recipeCount = 0;
    final itemByKey = <String, InventoryItem>{};
    for (final it in inventory) {
      itemByKey.putIfAbsent(it.name.trim().toLowerCase(), () => it);
    }
    InventoryItem needItem(String name, GroceryCategory category, StockUnit unit) {
      final q = name.trim().toLowerCase();
      final existing = itemByKey[q] ?? itemByName(name);
      if (existing != null) return existing;
      final created = InventoryItem(
        name: name,
        category: category,
        unit: unit,
        currentStock: 0,
        warehouseStock: 0,
        minThreshold: 0,
      );
      inventory.add(created);
      itemByKey[q] = created;
      itemCount++;
      return created;
    }

    final itemDef = <String, _OfficialItem>{};
    for (final e in _officialItems) {
      itemDef[e.name] = e;
    }
    for (final e in _officialItems) {
      needItem(e.name, e.category, e.unit);
    }
    for (final r in _officialRecipes) {
      if (findRecipeByName(r.name) != null) continue;
      final ings = <RecipeIngredient>[];
      for (final ing in r.ingredients) {
        final def = itemDef[ing.itemName];
        if (def == null) continue;
        final item = needItem(def.name, def.category, def.unit);
        ings.add(RecipeIngredient(
            itemId: item.id, amountPerServing: ing.amount));
      }
      if (ings.isEmpty) continue;
      recipes.add(Recipe(
        name: r.name,
        description: 'Resmi gramaj listesi (EK-1) - 1 porsiyon',
        servingsDefault: 1,
        ingredients: ings,
      ));
      recipeCount++;
    }
    await save();
    return {'items': itemCount, 'recipes': recipeCount};
  }
}
